# -*- coding: utf-8 -*-
"""kospi/data/069500_5m_<연도>.csv → 프로젝트 파일 kdata_NN.py (종가만, 사람이 읽는 평문, 파일당 ≤ 31,000자).
무료 조직은 Object Store 를 백테스트에서 못 읽고(2026-10-25 확인), 압축·인코딩 블롭은 약관상 저장 거부, 파일당 32,000자 제한이라
하루 한 줄 평문으로 둔다: "yyyyMMdd @HHMM c c c ... [@HHMM c ...]" — @HHMM 은 그 다음 종가의 봉 시작시각(KST), 이후 종가는 5분 간격.
시간이 건너뛰면(점심 없음, 수능일 15:30 이후 연장 등) @HHMM 을 다시 쓴다. 알고리즘은 initialize 에서 CSV 로 풀어 LOCAL_FILE 로 읽는다.
usage: .venv-quant/Scripts/python platforms/quantconnect/kospi/make_embed.py"""
import os, glob
from datetime import datetime, timedelta

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "embed"); os.makedirs(OUT, exist_ok=True)
LIMIT = 31000

HEADER = ('# KODEX200 (069500) 5-minute closes, plain text. One line per trading day:\n'
          '#   yyyyMMdd @HHMM close close ... [@HHMM close ...]\n'
          '# @HHMM = KST start time of the next close; following closes step +5 minutes; a new @HHMM marks a time jump.\n'
          '# Source: Creon 5m bars 2021-07~2026-08 + ALIGN3 executor bars ~2026-10 (kis_trader). Generated by make_embed.py.\n'
          'TXT = """\n')

for old in glob.glob(os.path.join(OUT, "kdata_*.py")):
    os.remove(old)
days = {}
for fn in sorted(glob.glob(os.path.join(HERE, "data", "069500_5m_*.csv"))):
    for l in open(fn, encoding="utf-8").read().splitlines()[1:]:
        p = l.split(",")
        d, hm = p[0][:8], p[0][9:11] + p[0][12:14]
        days.setdefault(d, []).append((hm, p[4]))
lines = []
for d in sorted(days):
    toks = [d]
    expect = None
    for hm, c in days[d]:
        if hm != expect:
            toks.append("@" + hm)
        toks.append(c)
        t = datetime.strptime(hm, "%H%M") + timedelta(minutes=5)
        expect = t.strftime("%H%M")
    lines.append(" ".join(toks))
chunks, cur, n = [], [], len(HEADER) + 4
for ln in lines:
    if n + len(ln) + 1 > LIMIT and cur:
        chunks.append(cur); cur, n = [], len(HEADER) + 4
    cur.append(ln); n += len(ln) + 1
if cur:
    chunks.append(cur)
for i, ch in enumerate(chunks, 1):
    body = HEADER + "\n".join(ch) + '\n"""\n'
    name = f"kdata_{i:02d}.py"
    open(os.path.join(OUT, name), "w", encoding="utf-8").write(body)
    print(name, f"{ch[0][:8]}~{ch[-1][:8]}", len(ch), "days", len(body), "chars")
print("files", len(chunks), "days", len(lines), "bars", sum(len(v) for v in days.values()))
